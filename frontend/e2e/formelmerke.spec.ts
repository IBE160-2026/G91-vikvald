import AxeBuilder from "@axe-core/playwright";
import { expect, test, type Locator, type Page } from "@playwright/test";

import { makePdf } from "./pdf";

// Story 6.3: a page with a formula drawn as vector curves gets needs_image at
// upload (FR-40), and what is made from it carries «Inneholder formel – sjekk
// mot kilden» directly above the source (FR-41), in demo mode too.

const PASSWORD = "hemmelig1";
const FLAG_TEXT = "Inneholder formel – sjekk mot kilden";
const LETTERS = ["a", "b", "c", "d"] as const;
// One definition per page (ASCII only); page 1 also has the drawn formula.
const PAGES = [
  "Elastisitet er endringen i mengde delt pa endringen i pris.",
  "Tilbud er mengden produsentene vil selge til en gitt pris.",
  "Likevekt er punktet der tilbud og etterspursel er like.",
  "Marginalkostnad er kostnaden ved a lage en enhet til.",
];

function uniqueEmail(): string {
  return `klara-${Date.now()}-${Math.random().toString(36).slice(2, 8)}@eksempel.no`;
}

async function expectNoAxeViolations(page: Page) {
  const results = await new AxeBuilder({ page }).analyze();
  expect(results.violations).toEqual([]);
}

type ApiQuestion = { question: string; options: string[]; correct_index: number; source: { page_no: number } };

// A logged-in student with one lecture made from the formula PDF and the
// content of `kind` generated by the mock model. Returns the lecture id.
async function lectureWithContent(page: Page, kind: "flashcards" | "quiz", pageCount: number): Promise<string> {
  const register = await page.request.post("/api/identity/register", {
    data: { email: uniqueEmail(), password: PASSWORD },
  });
  expect(register.status()).toBe(201);
  expect((await page.request.post("/api/identity/terms")).status()).toBe(200);
  const subject = await page.request.post("/api/subjects", { data: { name: "Samfunnsøkonomi", exam_date: "2026-12-04" } });
  const subjectId = (await subject.json()).id;
  const lecture = await page.request.post(`/api/subjects/${subjectId}/lectures`, {
    data: { name: "Uke 38: Elastisitet", date: "2026-09-18" },
  });
  const lectureId = (await lecture.json()).id;
  const pdf = makePdf({ pages: PAGES.slice(0, pageCount), formulaPages: [1] });
  const upload = await page.request.post(`/api/lectures/${lectureId}/files`, {
    multipart: { file: { name: "formler.pdf", mimeType: "application/pdf", buffer: pdf } },
  });
  expect(upload.status()).toBe(201);
  const body = kind === "quiz" ? { kind, params: { requested: 10, difficulty: "medium" } } : { kind };
  expect((await page.request.post(`/api/lectures/${lectureId}/jobs`, { data: body })).status()).toBe(202);
  const countKey = kind === "quiz" ? "quiz_questions" : "flashcards";
  await expect
    .poll(async () => (await (await page.request.get(`/api/lectures/${lectureId}/content-counts`)).json())[countKey], {
      timeout: 10_000,
    })
    .toBe(pageCount);
  return lectureId;
}

// The flag must be the element right before the source link.
async function expectFlagRightAboveSource(scope: Locator) {
  const flag = scope.locator('[data-slot="formula-flag"]');
  await expect(flag).toHaveText(FLAG_TEXT);
  await expect(flag.locator('xpath=following-sibling::*[1][@data-slot="source-link"]')).toHaveCount(1);
}

test.describe("Formelmerke (story 6.3)", () => {
  test("FR-40, FR-41: kort fra formelsiden har merket i øvingen og feillista, kort fra tekstsiden ikke", async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 900 });
    const lectureId = await lectureWithContent(page, "flashcards", 2);
    const cards = (await (await page.request.get(`/api/lectures/${lectureId}/flashcards`)).json()) as {
      source: { page_no: number };
      formula_flag: boolean;
    }[];
    expect(cards.map((card) => [card.source.page_no, card.formula_flag])).toEqual([
      [1, true],
      [2, false],
    ]);

    await page.goto(`/forelesninger/${lectureId}/flashcards`);
    const card = page.locator('[data-slot="flashcard"]');
    // First round «Kunne ikke» on both, then «Kunne» on both while repeating.
    for (const mark of ["Kunne ikke", "Kunne ikke", "Kunne", "Kunne"]) {
      await page.getByRole("button", { name: "Snu kortet" }).click();
      const source = await card.locator('[data-slot="source-link"]').textContent();
      if (source === "formler.pdf, side 1") {
        await expectFlagRightAboveSource(card);
        await expectNoAxeViolations(page);
      } else {
        expect(source).toBe("formler.pdf, side 2");
        await expect(card.locator('[data-slot="formula-flag"]')).toHaveCount(0);
      }
      await page.getByRole("button", { name: mark, exact: true }).click();
    }

    await expect(page.getByRole("heading", { level: 2, name: "Du har gått gjennom alle 2 kortene" })).toBeVisible();
    const rows = page.locator('[data-slot="missed-list"]').getByRole("listitem");
    await expect(rows).toHaveCount(2);
    const flagged = rows.filter({ hasText: "formler.pdf, side 1" });
    await expectFlagRightAboveSource(flagged);
    await expect(rows.filter({ hasText: "formler.pdf, side 2" }).locator('[data-slot="formula-flag"]')).toHaveCount(0);
    await expectNoAxeViolations(page);
  });

  test("FR-40, FR-41: quizspørsmål fra formelsiden har merket i forklaringen og feillista", async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 900 });
    const lectureId = await lectureWithContent(page, "quiz", 4);
    const questions = (await (await page.request.get(`/api/lectures/${lectureId}/quiz-questions`)).json()) as ApiQuestion[];

    await page.goto(`/forelesninger/${lectureId}/quiz`);
    const shown = page.locator('[data-slot="quiz-question"]');
    for (let number = 1; number <= questions.length; number += 1) {
      await expect(page.getByText(`SPØRSMÅL ${number} AV ${questions.length}`)).toBeVisible();
      const text = await shown.getByRole("heading", { level: 2 }).textContent();
      const question = questions.find((item) => item.question === text)!;
      // Always the wrong answer, so every question ends up in the missed list.
      await page.keyboard.press(LETTERS[(question.correct_index + 1) % 4]);
      await page.keyboard.press("Enter");
      const explanation = page.locator('[data-slot="explanation-card"]');
      await expect(explanation).toBeVisible();
      if (question.source.page_no === 1) {
        await expectFlagRightAboveSource(explanation);
        await expectNoAxeViolations(page);
      } else {
        await expect(explanation.locator('[data-slot="formula-flag"]')).toHaveCount(0);
      }
      await page.keyboard.press("Enter");
    }

    await expect(page.getByRole("heading", { level: 2, name: `0 av ${questions.length} riktige` })).toBeVisible();
    const rows = page.locator('[data-slot="missed-list"]').getByRole("listitem");
    await expect(rows).toHaveCount(questions.length);
    await expect(page.locator('[data-slot="missed-list"] [data-slot="formula-flag"]')).toHaveCount(1);
    await expectFlagRightAboveSource(rows.filter({ hasText: "formler.pdf, side 1" }));
    await expectNoAxeViolations(page);
  });
});
